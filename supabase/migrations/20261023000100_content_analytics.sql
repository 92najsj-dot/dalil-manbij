-- Phase 1: content analytics for Dalil Manbij.
-- This migration is staged in the preview branch only; it has NOT been applied to the live Supabase database.

create table if not exists public.content_analytics_events (
  id bigint generated by default as identity primary key,
  target_type text not null check (target_type in ('listing', 'business')),
  target_id uuid not null,
  event_type text not null check (event_type in ('view', 'whatsapp_click', 'call_click', 'favorite')),
  session_id uuid,
  created_at timestamptz not null default now()
);

create index if not exists content_analytics_target_created_idx
  on public.content_analytics_events (target_type, target_id, created_at desc);
create index if not exists content_analytics_event_type_created_idx
  on public.content_analytics_events (event_type, created_at desc);

-- A browser session can contribute at most one view per content item.
create unique index if not exists content_analytics_unique_session_view_idx
  on public.content_analytics_events (target_type, target_id, session_id)
  where event_type = 'view' and session_id is not null;

alter table public.content_analytics_events enable row level security;

revoke all on public.content_analytics_events from public;
grant insert on public.content_analytics_events to anon, authenticated;
grant select on public.content_analytics_events to authenticated;
grant usage, select on sequence public.content_analytics_events_id_seq to anon, authenticated;

drop policy if exists "Public can record analytics for active content" on public.content_analytics_events;
create policy "Public can record analytics for active content"
on public.content_analytics_events
for insert
to anon, authenticated
with check (
  event_type in ('view', 'whatsapp_click', 'call_click', 'favorite')
  and (
    (target_type = 'listing' and exists (
      select 1 from public.listings l
      where l.id = target_id and l.status = 'active'
    ))
    or
    (target_type = 'business' and exists (
      select 1 from public.businesses b
      where b.id = target_id and b.status = 'active'
    ))
  )
);

drop policy if exists "Owners can read analytics for their content" on public.content_analytics_events;
create policy "Owners can read analytics for their content"
on public.content_analytics_events
for select
to authenticated
using (
  (target_type = 'listing' and exists (
    select 1 from public.listings l
    where l.id = target_id and l.user_id = (select auth.uid())
  ))
  or
  (target_type = 'business' and exists (
    select 1 from public.businesses b
    where b.id = target_id and b.owner_id = (select auth.uid())
  ))
);
